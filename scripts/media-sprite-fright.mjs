#!/usr/bin/env node
// Builds the self-hosted HLS clip the bench's `hls` position plays
// (`apps/site/src/bench-sources.ts`).
//
// ---- the source ------------------------------------------------------------
//
// _Sprite Fright_ (2021), Blender Studio's thirteenth open movie, CC BY 4.0.
// The film itself is not on `download.blender.org/demo/movies/` or its
// `ftp.nluug.nl` mirror -- both were checked and neither carries it -- and
// `studio.blender.org/films/sprite-fright/` gates its own download behind a
// Blender Studio subscription. What is not gated is Blender's own PeerTube
// instance, `video.blender.org`: the film is published there by the official
// `blender` account, in the `blender_open_movies` channel, as
// "Sprite Fright - Open Movie by Blender Studio" -- a first-party Blender
// release, not a third-party reupload, and PeerTube serves a direct file for
// it rather than gating one behind a login. `SOURCE_URL` below is that
// release's own 1920x804 rendition (PeerTube's API calls it "1080p"; the
// letterboxed frame is short of that, the way the film's every release is
// short of a plain 16:9 tag). `SOURCE_SIZE_BYTES` and `SOURCE_SHA256` are
// this exact file's, read off the download and cross-checked against an
// independent CC BY 4.0 archive.org mirror's embedded MediaInfo tags before
// this script existed, and are what `ensureSourceFilm` below verifies every
// run against -- so a file that arrives corrupted, truncated, or is silently
// replaced at that address fails loudly here rather than becoming this
// project's clip.
//
// ---- the clip ---------------------------------------------------------------
//
// `CLIP_START_SECONDS` through `CLIP_START_SECONDS + CLIP_DURATION_SECONDS`
// is the film's own discovery-of-the-mushroom-creatures scene: past the
// title card and the opening hike, in daylight throughout, and cut before the
// story turns to its darker night scenes -- the same criteria
// `bench-sources.ts`'s own note on the `youtube`/`vimeo` poster names for
// picking a single frame, applied here to picking ninety seconds. Chosen by
// sampling frames across the film's ten and a half minutes and reading them,
// not by a timestamp guessed in advance.
//
// ---- the ladder ---------------------------------------------------------------
//
// Three video renditions sharing one audio track, `EXT-X-MEDIA` group
// `audio` -- an adaptive ladder a single-file `<video src>` cannot express,
// which is the whole reason this position is worth having beside `youtube`
// and `vimeo` rather than a fourth link to somewhere else. Every rendition's
// frame is an exact integer division of the source's own 1920x804 -- 1x, 1.5x
// and 3x -- so none of the three is a scaler's rounding of the film's own
// ratio. Segments are `hls_time`-cut at a fixed six seconds with scene-cut
// detection off (`sc_threshold 0`) and a GOP pinned to that same six seconds,
// so a segment boundary is always a keyframe boundary and never a guess.
//
// ---- idempotency and the cache ---------------------------------------------
//
// Two directories, and neither is this repository. `PLAYDECK_MEDIA_CACHE_DIR`
// (default: a directory under the OS temp dir) holds the downloaded film,
// verified and reused rather than re-fetched on every run. The generated
// ladder and posters land directly under `apps/site/public/`, which
// `.gitignore` excludes for the same reason `dist/` is: they are build
// output, not source, and are regenerated by `apps/site/package.json`'s
// `build` and `build:based` scripts before `astro build` ever reads
// `public/`. `buildSpriteFrightMedia` below checks for that output first and
// returns immediately when it is already there, so a warm machine pays this
// script's cost once rather than on every build.
//
// Both writers below stage into a sibling `*.tmp` path on the same device as
// their destination and `rename` into place only once ffmpeg has exited
// zero, rather than writing the destination directly or staging under the OS
// temp dir (commonly a different filesystem, where `rename` would fail
// cross-device) -- so a run interrupted midway never leaves a partially
// written directory that the idempotency check above would mistake for a
// finished one.

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { createWriteStream } from 'node:fs';
import { mkdir, readFile, rename, rm, stat } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import process from 'node:process';
import { Readable } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import { fileURLToPath } from 'node:url';

// As in scripts/assemble-deploy.mjs and scripts/serve-site.mjs: the lint
// config gives this directory Node globals, but `console`, `process` and
// `fetch` still have to be reached through `globalThis`.
const console = globalThis.console;
const fetch = globalThis.fetch;

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// ---- the source film --------------------------------------------------------

export const SOURCE_URL =
  'https://video.blender.org/download/web-videos/a69d68a5-a0e0-4a80-9d66-49f093c97aaf-804.mp4';
export const SOURCE_SIZE_BYTES = 110581245;
export const SOURCE_SHA256 =
  '85af52d5f82976256d5f091aea4cf276a3d8599d14d36bae5d51e43a9acfd076';
/** The source's own encoded frame size -- see the header note above. */
export const SOURCE_WIDTH = 1920;
export const SOURCE_HEIGHT = 804;

// ---- the clip ----------------------------------------------------------------

export const CLIP_START_SECONDS = 154;
export const CLIP_DURATION_SECONDS = 90;
/** Absolute, not relative to the clip: a frame ffmpeg extracts directly from
 * the downloaded source for the poster. Falls inside the clip window above. */
export const POSTER_TIME_SECONDS = 200;

const SEGMENT_SECONDS = 6;
/** The source's own constant frame rate, confirmed with `ffprobe`. */
const SOURCE_FPS = 24;

/**
 * @typedef {{ readonly name: string; readonly width: number; readonly height: number; readonly videoBitrateKbps: number }} Rendition
 */

/** @type {readonly Rendition[]} */
const RENDITIONS = [
  { name: '1080p', width: 1920, height: 804, videoBitrateKbps: 1800 },
  { name: '720p', width: 1280, height: 536, videoBitrateKbps: 900 },
  { name: '360p', width: 640, height: 268, videoBitrateKbps: 350 }
];
const AUDIO_BITRATE_KBPS = 96;

/** Exact integer divisions of the source's own frame: 1x and its exact half. */
const POSTER_WIDTHS = [960, 1920];

const outputDir = join(repoRoot, 'apps/site/public/media/sprite-fright');
const posterDir = join(repoRoot, 'apps/site/public');
const posterBase = 'sprite-fright-hls-poster';

/** @returns {string} */
const cacheDir = () =>
  process.env.PLAYDECK_MEDIA_CACHE_DIR ??
  join(tmpdir(), 'playdeck-media-cache');

/** @returns {string} */
const cachedFilmPath = () => join(cacheDir(), 'sprite-fright-source.mp4');

/**
 * @param {string} filePath
 * @returns {Promise<string>}
 */
const sha256File = async (filePath) =>
  createHash('sha256')
    .update(await readFile(filePath))
    .digest('hex');

/**
 * @param {string} destination
 * @returns {Promise<void>}
 */
const downloadSourceFilm = async (destination) => {
  console.log(`Downloading ${SOURCE_URL}`);
  const response = await fetch(SOURCE_URL);
  if (!response.ok || response.body === null) {
    throw new Error(
      `Failed to download the source film: HTTP ${response.status} from ${SOURCE_URL}`
    );
  }
  await mkdir(dirname(destination), { recursive: true });
  const tmpPath = `${destination}.download`;
  await pipeline(
    Readable.fromWeb(/** @type {never} */ (response.body)),
    createWriteStream(tmpPath)
  );
  await rename(tmpPath, destination);
};

/**
 * The verified, cached source film -- downloaded and checked against
 * `SOURCE_SIZE_BYTES`/`SOURCE_SHA256` if it is not already present and
 * correct. Throws rather than proceeding on a mismatch of either: a source
 * that does not match what this file's header records as verified must never
 * silently become the clip this project ships.
 *
 * @returns {Promise<string>}
 */
const ensureSourceFilm = async () => {
  const destination = cachedFilmPath();
  const cached = await stat(destination).catch(() => null);
  if (cached?.isFile() && cached.size === SOURCE_SIZE_BYTES) {
    if ((await sha256File(destination)) === SOURCE_SHA256) {
      console.log(`Using cached source film at ${destination}`);
      return destination;
    }
    console.log(
      'Cached source film failed checksum verification; re-downloading.'
    );
  }
  await downloadSourceFilm(destination);
  const downloaded = await stat(destination);
  if (downloaded.size !== SOURCE_SIZE_BYTES) {
    throw new Error(
      `Downloaded film is ${downloaded.size} bytes, expected ${SOURCE_SIZE_BYTES}. Refusing a source that does not match what was verified.`
    );
  }
  const digest = await sha256File(destination);
  if (digest !== SOURCE_SHA256) {
    throw new Error(
      `Downloaded film's SHA-256 is ${digest}, expected ${SOURCE_SHA256}. Refusing a source that does not match what was verified.`
    );
  }
  return destination;
};

/** @returns {void} */
const assertFfmpegAvailable = () => {
  try {
    execFileSync('ffmpeg', ['-version'], { stdio: 'ignore' });
  } catch {
    throw new Error(
      'ffmpeg is required to build the Sprite Fright clip and was not found on PATH.'
    );
  }
};

/**
 * The `ffmpeg` invocation that cuts the clip and encodes the whole ladder in
 * one pass: one decode of the source, split three ways and scaled per
 * rendition, muxed into HLS with a shared audio group.
 *
 * @param {string} sourcePath
 * @param {string} outDir
 * @returns {readonly string[]}
 */
const buildFfmpegHlsArgs = (sourcePath, outDir) => {
  const gop = String(SEGMENT_SECONDS * SOURCE_FPS);
  const splitLabels = RENDITIONS.map((_, index) => `[v${index}]`).join('');
  const scaleFilters = RENDITIONS.map(
    (rendition, index) =>
      `[v${index}]scale=w=${rendition.width}:h=${rendition.height}[v${index}out]`
  ).join(';');
  const filterComplex = `[0:v]split=${RENDITIONS.length}${splitLabels};${scaleFilters}`;

  /** @type {string[]} */
  const args = [
    '-y',
    '-ss',
    String(CLIP_START_SECONDS),
    '-i',
    sourcePath,
    '-t',
    String(CLIP_DURATION_SECONDS),
    '-filter_complex',
    filterComplex,
    '-pix_fmt',
    'yuv420p'
  ];

  RENDITIONS.forEach((rendition, index) => {
    const maxrateKbps = Math.round(rendition.videoBitrateKbps * 1.07);
    const bufsizeKbps = Math.round(rendition.videoBitrateKbps * 1.5);
    args.push(
      '-map',
      `[v${index}out]`,
      `-c:v:${index}`,
      'libx264',
      `-profile:v:${index}`,
      'main',
      `-b:v:${index}`,
      `${rendition.videoBitrateKbps}k`,
      `-maxrate:v:${index}`,
      `${maxrateKbps}k`,
      `-bufsize:v:${index}`,
      `${bufsizeKbps}k`,
      `-g:v:${index}`,
      gop,
      `-keyint_min:v:${index}`,
      gop,
      `-sc_threshold:v:${index}`,
      '0'
    );
  });

  args.push(
    '-map',
    'a:0',
    '-c:a',
    'aac',
    '-b:a',
    `${AUDIO_BITRATE_KBPS}k`,
    '-ac',
    '2',
    '-ar',
    '44100'
  );

  const varStreamMap = [
    ...RENDITIONS.map(
      (rendition, index) => `v:${index},agroup:audio,name:${rendition.name}`
    ),
    'a:0,agroup:audio,name:audio,default:yes'
  ].join(' ');

  args.push(
    '-var_stream_map',
    varStreamMap,
    '-master_pl_name',
    'master.m3u8',
    '-f',
    'hls',
    '-hls_time',
    String(SEGMENT_SECONDS),
    '-hls_playlist_type',
    'vod',
    '-hls_flags',
    'independent_segments',
    '-hls_segment_filename',
    join(outDir, '%v', 'seg_%03d.ts'),
    join(outDir, '%v', 'prog.m3u8')
  );

  return args;
};

/**
 * @param {string} sourcePath
 * @returns {Promise<void>}
 */
const encodeHlsLadder = async (sourcePath) => {
  const tmpDir = `${outputDir}.tmp`;
  await rm(tmpDir, { recursive: true, force: true });
  await mkdir(tmpDir, { recursive: true });
  try {
    execFileSync('ffmpeg', buildFfmpegHlsArgs(sourcePath, tmpDir), {
      stdio: 'inherit'
    });
    await rm(outputDir, { recursive: true, force: true });
    // `tmpDir` is `${outputDir}.tmp`, next to `outputDir` and therefore on the
    // same device, so this `rename` is the atomic swap the header comment
    // above promises rather than a copy that could be interrupted midway.
    await rename(tmpDir, outputDir);
  } catch (error) {
    await rm(tmpDir, { recursive: true, force: true }).catch(() => {});
    throw error;
  }
};

/**
 * @param {string} sourcePath
 * @returns {Promise<void>}
 */
const exportPosters = async (sourcePath) => {
  await mkdir(posterDir, { recursive: true });
  for (const width of POSTER_WIDTHS) {
    // Exact: both widths evenly divide the source's own frame, so this is
    // never a scaler's rounding of the ratio.
    const height = Math.round((width / SOURCE_WIDTH) * SOURCE_HEIGHT);
    const finalPath = join(posterDir, `${posterBase}-${width}w.webp`);
    // `.tmp` rather than `.webp.tmp` would still be same-directory and still
    // rename atomically, but ffmpeg picks its muxer from the output filename's
    // own extension and `.tmp` is not one it recognises -- `-f webp` says so
    // explicitly instead, which is what lets the staged file keep a `.tmp`
    // suffix without ffmpeg refusing to write it.
    const tmpPath = `${finalPath}.tmp`;
    execFileSync(
      'ffmpeg',
      [
        '-y',
        '-ss',
        String(POSTER_TIME_SECONDS),
        '-i',
        sourcePath,
        '-frames:v',
        '1',
        '-vf',
        `scale=${width}:${height}`,
        '-q:v',
        '90',
        '-f',
        'webp',
        tmpPath
      ],
      { stdio: 'inherit' }
    );
    // Same directory as the destination, so this `rename` is the same
    // same-device atomic swap `encodeHlsLadder` performs.
    await rename(tmpPath, finalPath);
  }
};

/**
 * Whether every file `bench-sources.ts`'s `hls` entry addresses already
 * exists, so a warm machine can skip the download and the encode entirely.
 *
 * @returns {Promise<boolean>}
 */
const outputsExist = async () => {
  const master = await stat(join(outputDir, 'master.m3u8')).catch(() => null);
  if (!master?.isFile()) return false;
  for (const width of POSTER_WIDTHS) {
    const posterStat = await stat(
      join(posterDir, `${posterBase}-${width}w.webp`)
    ).catch(() => null);
    if (!posterStat?.isFile()) return false;
  }
  return true;
};

/** @returns {Promise<void>} */
export const buildSpriteFrightMedia = async () => {
  if (await outputsExist()) {
    console.log(`Sprite Fright media already built at ${outputDir}; skipping.`);
    return;
  }
  assertFfmpegAvailable();
  const sourcePath = await ensureSourceFilm();
  console.log(
    `Encoding a ${CLIP_DURATION_SECONDS}s clip from ${CLIP_START_SECONDS}s into ${outputDir}`
  );
  await encodeHlsLadder(sourcePath);
  console.log(`Exporting posters into ${posterDir}`);
  await exportPosters(sourcePath);
  console.log('Sprite Fright media built.');
};

// Only when run as a command, as in scripts/assemble-deploy.mjs -- an import
// must not build anything as a side effect.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await buildSpriteFrightMedia();
}
