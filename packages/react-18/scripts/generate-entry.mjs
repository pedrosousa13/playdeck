// Generates `src/entry.tsx` from `../react/src/index.tsx`'s own top-level
// `export { ... } from '...'` / `export type { ... } from '...'` statements,
// so the list of which exports get wrapped in `forwardRef` is read off the
// unchanged source on every build rather than hand-maintained here.
//
// A plain-function value export is wrapped exactly when its name is
// PascalCase (starts with an uppercase letter) -- every component in
// `../react/src` is named that way, and every hook/helper (`usePlayerState`,
// `normalizePoster`, ...) is not, so this one check sorts every current and
// future export correctly without reading its type. Wrapping an icon in
// `forwardRef` too costs nothing: the spike's design notes wrapping every
// PascalCase function export is fine, rather than special-casing the ~32
// that actually declare a `ref`.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, URL } from 'node:url';
import console from 'node:console';

const here = fileURLToPath(new URL('.', import.meta.url));
const sourceIndexPath = fileURLToPath(
  new URL('../../react/src/index.tsx', import.meta.url)
);
const source = readFileSync(sourceIndexPath, 'utf8');

const exportBlockPattern =
  /export\s+(type\s+)?\{([\s\S]*?)\}\s*from\s*['"]([^'"]+)['"]/g;

const typeNames = new Set();
const valueNames = new Set();

for (const match of source.matchAll(exportBlockPattern)) {
  const [, isType, body] = match;
  const names = body
    .split(',')
    .map((entry) => entry.trim())
    .filter((entry) => entry.length > 0)
    .map((entry) => {
      // Handles a renamed specifier (`Foo as Bar`); none exist in
      // ../react/src/index.tsx today, but this keeps the generator correct
      // if one is ever added.
      const asMatch = entry.match(/^(\S+)\s+as\s+(\S+)$/);
      return asMatch ? asMatch[2] : entry;
    });
  for (const name of names) {
    if (isType) typeNames.add(name);
    else valueNames.add(name);
  }
}

const isPascalCase = (name) => /^[A-Z]/.test(name);

const wrappedValueNames = [...valueNames].filter(isPascalCase).sort();
const passthroughValueNames = [...valueNames]
  .filter((name) => !isPascalCase(name))
  .sort();
const sortedTypeNames = [...typeNames].sort();

if (wrappedValueNames.length === 0) {
  throw new Error(
    'generate-entry: parsed zero PascalCase value exports out of ' +
      sourceIndexPath +
      ' -- the export-block regex likely stopped matching its shape.'
  );
}

const lines = [];
lines.push(
  // Carried over from `../react/src/index.tsx`'s own first line. A
  // directive only hoists out of the chunk that opens with it; `index.tsx`
  // is a transitively-imported module in THIS package's build, not the lib
  // entry Vite reads, so without repeating it here, nothing in the output
  // bundle would open with it at all and an RSC build consuming this
  // package would fail the same way scripts/client-boundary.mjs's check
  // exists to catch for @playdeck/react (confirmed: scripts/verify-packaging.mjs's
  // `use client` check fails against this package without this line).
  "'use client';",
  '',
  "// GENERATED by scripts/generate-entry.mjs from ../react/src/index.tsx's",
  "// own export list -- do not hand-edit. Re-run the package's build to",
  '// regenerate after `../react/src/index.tsx` changes which names it',
  '// exports.',
  "import { forwardRef, type ReactNode } from 'react';",
  "import * as Source from '../../react/src/index.js';",
  '',
  'export type {',
  ...sortedTypeNames.map((name) => `  ${name},`),
  "} from '../../react/src/index.js';",
  ''
);

for (const name of passthroughValueNames) {
  lines.push(`export const ${name} = Source.${name};`);
}

lines.push(
  '',
  '// Every plain function component in ../react/src reads `ref` straight off',
  "// its own props (React 19's shape); React 18 never hands a plain function",
  "// component a `ref` prop at all, so a consumer's own JSX -- compiled by",
  "// their own React 18 jsx-runtime, not this package's internal shim -- needs",
  '// a real `forwardRef` component at this public boundary for `ref` to reach',
  '// it. Cheap enough to apply to every PascalCase export, icons included,',
  '// rather than track down exactly which ones declare `ref` in their props.'
);
lines.push(
  'const wrapWithForwardRef = <P extends object>(',
  '  Component: (props: P) => ReactNode,',
  '  displayName: string',
  ') => {',
  '  const Wrapped = forwardRef((props: P, ref: unknown) =>',
  '    Component({ ...props, ref } as P)',
  '  );',
  '  (Wrapped as { displayName?: string }).displayName = displayName;',
  '  return Wrapped;',
  '};',
  ''
);

for (const name of wrappedValueNames) {
  lines.push(
    `export const ${name} = wrapWithForwardRef(Source.${name}, '${name}');`
  );
}

lines.push('');

writeFileSync(new URL('../src/entry.tsx', `file://${here}`), lines.join('\n'));

console.log(
  `generate-entry: wrapped ${wrappedValueNames.length} component export(s), ` +
    `passed through ${passthroughValueNames.length} value export(s), ` +
    `forwarded ${sortedTypeNames.length} type export(s).`
);
